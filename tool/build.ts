import { spawn } from "node:child_process";
import { closeSync, existsSync, mkdirSync, openSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { homedir } from "node:os";
import { Data, Effect, Either, Schema } from "effect";
import { parseComponent, type ComponentSource, type ParseComponentError } from "./parse-component.ts";

export { parseComponent } from "./parse-component.ts";

const marker = "-- Generated by elm-web-components. Do not edit.";

export type BuildOptions = { app?: string; output?: string; componentFiles: string[]; optimize?: boolean };

const ElmApplication = Schema.Struct({
  type: Schema.Literal("application"),
  "source-directories": Schema.Array(Schema.String),
  "elm-version": Schema.String,
  dependencies: Schema.Struct({
    direct: Schema.Record({ key: Schema.String, value: Schema.String }),
    indirect: Schema.Record({ key: Schema.String, value: Schema.String }),
  }),
  "test-dependencies": Schema.Unknown,
});

type ElmApplication = typeof ElmApplication.Type;

/** A build configuration, filesystem, or Elm compiler failure. */
export class BuildError extends Data.TaggedError("BuildError")<{ readonly stage: string; readonly message: string; readonly cause?: unknown }> {}

function buildFailure(stage: string, cause: unknown): BuildError {
  return new BuildError({ stage, message: cause instanceof Error ? cause.message : `${stage}: ${String(cause)}`, cause });
}

const fail = (path: string, message: string): never => {
  throw new Error(`${path}: ${message}`);
};

export function generatedElm(component: ComponentSource): string {
  return component.elm;
}

export function generatedHost(component: ComponentSource): string {
  return component.host;
}

export function generatedAdapter(component: ComponentSource): string {
  return component.adapter;
}

function elmBinary(project: string): string {
  if (process.env.ELM_BINARY) return process.env.ELM_BINARY;
  let directory = project;

  while (true) {
    const local = resolve(directory, "node_modules/.bin/elm");

    if (existsSync(local)) return local;
    const parent = dirname(directory);

    if (parent === directory) return "elm";
    directory = parent;
  }
}

function removeGeneratedHosts(directory: string): void {
  if (!existsSync(directory)) return;

  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);

    if (entry.isDirectory()) removeGeneratedHosts(path);
    else if (entry.name.endsWith(".elm") && readFileSync(path, "utf8").startsWith(marker)) unlinkSync(path);
  }
}


function projectModules(directory: string): Array<{ path: string; contents: string }> {
  if (!existsSync(directory)) return [];

  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name === "WebComponents") return [];
    const path = resolve(directory, entry.name);

    if (entry.isDirectory()) return projectModules(path);

    if (!entry.name.endsWith(".elm")) return [];

    return [{ path, contents: readFileSync(path, "utf8") }];
  });
}

function packageDocs(elmJson: ElmApplication): Array<{ name: string; docs: string }> {
  const home = process.env.ELM_HOME ?? resolve(homedir(), ".elm");
  const dependencies = { ...elmJson.dependencies.direct, ...elmJson.dependencies.indirect };

  return Object.entries(dependencies).flatMap(([name, version]) => {
    const path = resolve(home, elmJson["elm-version"], "packages", name, version, "docs.json");

    return existsSync(path) ? [{ name, docs: readFileSync(path, "utf8") }] : [];
  });
}

function acquireBuildLock(project: string): Effect.Effect<{ readonly descriptor: number; readonly path: string }, BuildError> {
  const directory = resolve(project, ".elm-web-components");
  const path = resolve(directory, "build.lock");

  return Effect.try({
    try: () => {
      mkdirSync(directory, { recursive: true });
      const descriptor = openSync(path, "wx");

      try {
        writeFileSync(descriptor, String(process.pid));
      } catch (cause) {
        closeSync(descriptor);
        unlinkSync(path);
        throw cause;
      }

      return { descriptor, path };
    },
    catch: (cause) => cause instanceof Error && "code" in cause && cause.code === "EEXIST"
      ? new BuildError({ stage: path, message: `${path}: another build is running; remove this lock only if that build has stopped`, cause })
      : buildFailure(path, cause),
  });
}

/** Build all components and an optional Elm app in one JavaScript bundle. */
export function build({ app, output = "dist/components.js", componentFiles, optimize = false }: BuildOptions, project = process.cwd()): Effect.Effect<void, BuildError | ParseComponentError> {
  return Effect.gen(function* () {
    if (!componentFiles?.length) return yield* Effect.fail(new BuildError({ stage: "build", message: "build: pass at least one component Elm file" }));

    if (!output.endsWith(".js")) return yield* Effect.fail(new BuildError({ stage: "build", message: "build: --output must end in .js" }));

    const manifestPath = resolve(project, "elm.json");

    const manifestText = yield* Effect.try({
      try: () => readFileSync(manifestPath, "utf8"),
      catch: (cause) => buildFailure(manifestPath, cause),
    });

    const elmJson = yield* Schema.decode(Schema.parseJson(ElmApplication))(manifestText).pipe(
      Effect.mapError((cause) => new BuildError({ stage: manifestPath, message: "elm.json: expected an Elm application with source-directories and valid dependencies", cause })),
    );

    const sources = elmJson["source-directories"].map((dir) => resolve(project, dir));

    if (!sources.length) return yield* Effect.fail(new BuildError({ stage: manifestPath, message: "elm.json: expected at least one source directory" }));
    const modules = yield* Effect.try({ try: () => sources.flatMap(projectModules), catch: (cause) => buildFailure("project modules", cause) });
    const packages = yield* Effect.try({ try: () => packageDocs(elmJson), catch: (cause) => buildFailure("package docs", cause) });

    const components = yield* Effect.forEach(componentFiles, (file) => Effect.gen(function* () {
      const path = resolve(project, file);
      const sourceRoot = sources.find((source) => path.startsWith(source + sep));

      if (!sourceRoot) return yield* Effect.fail(new BuildError({ stage: file, message: `${file}: component must be inside an Elm source directory` }));
      const component = yield* parseComponent(path, modules, packages);
      const expected = resolve(sourceRoot, ...component.module.split(".")) + ".elm";

      if (path !== expected) return yield* Effect.fail(new BuildError({ stage: file, message: `${file}: module ${component.module} must be at ${expected}` }));

      return component;
    }), { concurrency: "unbounded" });

    yield* Effect.try({
      try: () => {
        const tags = new Set<string>();

        for (const component of components) {
          if (tags.has(component.tag)) fail(component.path, `duplicate tag ${component.tag}`);
          tags.add(component.tag);
          const path = resolve(sources[0], "WebComponents", ...component.module.split(".")) + ".elm";

          if (existsSync(path) && !readFileSync(path, "utf8").startsWith(marker)) fail(path, "generated host module would overwrite a handwritten file");
          const codecPath = resolve(sources[0], "WebComponents", "Codecs", component.suffix + ".elm");

          if (existsSync(codecPath) && !readFileSync(codecPath, "utf8").startsWith(marker)) fail(codecPath, "generated codec module would overwrite a handwritten file");
        }
      },
      catch: (cause) => buildFailure("preflight", cause),
    });

    return yield* Effect.uninterruptibleMask((restore) => Effect.gen(function* () {
      const lock = yield* acquireBuildLock(project);

      const buildExit = yield* Effect.exit(restore(Effect.gen(function* () {
        const { buildDirectory, compiled, args } = yield* Effect.try({
          try: () => {
            removeGeneratedHosts(resolve(sources[0], "WebComponents"));

            for (const component of components) {
              const path = resolve(sources[0], "WebComponents", ...component.module.split(".")) + ".elm";
              mkdirSync(dirname(path), { recursive: true });
              writeFileSync(path, generatedHost(component));
              const codecPath = resolve(sources[0], "WebComponents", "Codecs", component.suffix + ".elm");
              mkdirSync(dirname(codecPath), { recursive: true });
              writeFileSync(codecPath, component.codec);
            }

            const buildDirectory = resolve(project, ".elm-web-components", "bundle");

            const entries = components.map((component) => {
              const name = `src/ElmWebComponents/Generated/${component.suffix}.elm`;
              const path = resolve(buildDirectory, name);
              mkdirSync(dirname(path), { recursive: true });
              writeFileSync(path, generatedElm(component));

              return name;
            });

            writeFileSync(resolve(buildDirectory, "elm.json"), JSON.stringify({
              ...elmJson,
              "source-directories": ["src", ...sources.map((source) => relative(buildDirectory, source))],
            }, null, 4) + "\n");
            const compiled = resolve(buildDirectory, "compiled.js");
            const args = ["make", ...entries, ...(app ? [resolve(project, app)] : []), `--output=${compiled}`, ...(optimize ? ["--optimize"] : [])];

            return { buildDirectory, compiled, args };
          },
          catch: (cause) => buildFailure("generated files", cause),
        });

        yield* Effect.async<void, BuildError>((resume) => {
          const child = spawn(elmBinary(project), args, { cwd: buildDirectory, env: process.env, stdio: "inherit" });
          let closed = false;
          let spawnError: Error | undefined;

          child.once("error", (cause) => { spawnError = cause; });
          child.once("close", (status) => {
            closed = true;
            resume(spawnError
              ? Effect.fail(buildFailure("Elm compiler", spawnError))
              : status === 0
                ? Effect.void
                : Effect.fail(new BuildError({ stage: "Elm compiler", message: "Elm build failed." })));
          });

          return Effect.async<void>((finish) => {
            if (closed) {
              finish(Effect.void);

              return;
            }

            const onClose = (): void => { clearTimeout(timer); finish(Effect.void); };

            const timer = setTimeout(() => { child.kill("SIGKILL"); }, 2000);
            child.once("close", onClose);
            child.kill("SIGTERM");

            return Effect.sync(() => { clearTimeout(timer); child.off("close", onClose); });
          });
        });

        yield* Effect.try({
          try: () => {
            const destination = resolve(project, output);
            mkdirSync(dirname(destination), { recursive: true });
            writeFileSync(destination, readFileSync(compiled, "utf8") + components.map(generatedAdapter).join(""));
            process.stdout.write(`Built ${relative(project, destination)}: ${components.map((c) => `<${c.tag}>`).join(", ")}${app ? ` and ${app}` : ""}\n`);
          },
          catch: (cause) => buildFailure("output bundle", cause),
        });
      })));

      const cleanup = yield* Effect.either(Effect.try({
        try: () => {
          const errors: unknown[] = [];

          try { closeSync(lock.descriptor); } catch (cause) { errors.push(cause); }

          try { unlinkSync(lock.path); } catch (cause) { errors.push(cause); }

          if (errors.length) throw new AggregateError(errors, `${lock.path}: could not release build lock`);
        },
        catch: (cause) => buildFailure(lock.path, cause),
      }));

      if (Either.isLeft(cleanup)) return yield* Effect.fail(cleanup.left);

      return yield* buildExit;
    }));
  });
}
